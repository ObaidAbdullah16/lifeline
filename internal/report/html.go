// HTML renders a self-contained report page.
func HTML(r *checks.Report) string {
	var b strings.Builder
	b.WriteString("<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">")
	fmt.Fprintf(&b, "<title>Lifeline scorecard</title><style>%s</style></head><body><main>", css)
	fmt.Fprintf(&b, "<h1>Lifeline resilience scorecard</h1><div class=\"muted\">%s &middot; %s</div>", html.EscapeString(target(r)), r.GeneratedAt.Format("2006-01-02 15:04 UTC"))
	b.WriteString("<div class=\"hero\">")
	fmt.Fprintf(&b, "<div class=\"card\"><div class=\"muted\">Overall</div><div class=\"big\">%.1f<span class=\"muted\" style=\"font-size:18px\">/10</span></div><div>%s &middot; coverage %.0f%%</div></div>", r.Score, gradeOf(r), r.Coverage*100)
	for _, cat := range checks.Categories {
		val := "n/a"
		if s, ok := r.Categories[cat]; ok {
			val = fmt.Sprintf("%.1f", s)
		}
		fmt.Fprintf(&b, "<div class=\"card\"><div class=\"muted\">%s</div><div class=\"cat\">%s</div></div>", html.EscapeString(cat), val)
	}
	b.WriteString("</div><table><thead><tr><th>Status</th><th>Check</th><th>Result</th><th>How to fix</th></tr></thead><tbody>")
	for _, res := range r.Results {
		fmt.Fprintf(&b, "<tr><td class=\"st %s\">%s</td><td><code>%s</code><br>%s</td><td>%s", res.Status, strings.ToUpper(string(res.Status)), res.ID, html.EscapeString(res.Title), html.EscapeString(res.Summary))
		if len(res.Details) > 0 {
			b.WriteString("<ul>")
			for _, d := range res.Details {
				fmt.Fprintf(&b, "<li>%s</li>", html.EscapeString(d))
			}
			b.WriteString("</ul>")
		}
		fix := ""
		if res.Status == checks.Fail || res.Status == checks.Warn {
			fix = html.EscapeString(res.Remediation)
		}
		fmt.Fprintf(&b, "</td><td>%s</td></tr>", fix)
	}
	b.WriteString("</tbody></table><p class=\"muted\">Generated by <a href=\"https://github.com/ObaidAbdullah16/lifeline\">Lifeline</a> ")
	fmt.Fprintf(&b, "%s. Skipped checks need a token, a domain or a lifeline.yml.</p></main></body></html>\n", html.EscapeString(r.Version))
	return b.String()
}
