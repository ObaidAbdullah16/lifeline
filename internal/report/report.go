// Package report renders a scan as text, JSON, Markdown, SARIF or a badge.
package report

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/ObaidAbdullah16/lifeline/internal/checks"
)

var icon = map[checks.Status]string{
	checks.Pass: "PASS", checks.Warn: "WARN", checks.Fail: "FAIL", checks.Skip: "SKIP", checks.Error: "ERR ",
}

var emoji = map[checks.Status]string{
	checks.Pass: "✅", checks.Warn: "⚠️", checks.Fail: "❌", checks.Skip: "⏭️", checks.Error: "💥",
}

// Grade turns a 0-10 score into a word.
func Grade(score float64) string {
	switch {
	case score >= 8.5:
		return "strong"
	case score >= 7:
		return "good"
	case score >= 5:
		return "fragile"
	}
	return "at risk"
}

// gradeOf is Grade, except that a scan in which no check could run has no grade.
func gradeOf(r *checks.Report) string {
	if r.Coverage == 0 {
		return "not evaluated"
	}
	return Grade(r.Score)
}

func target(r *checks.Report) string {
	parts := []string{}
	if r.Repo != "" {
		parts = append(parts, r.Repo)
	}
	if r.Domain != "" {
		parts = append(parts, r.Domain)
	}
	if len(parts) == 0 {
		return "(local checkout)"
	}
	return strings.Join(parts, " / ")
}

// Text is the terminal output.
func Text(r *checks.Report) string {
	var b strings.Builder
	fmt.Fprintf(&b, "Lifeline %s  %s\n", r.Version, target(r))
	fmt.Fprintf(&b, "SCORE %.1f/10 (%s)  coverage %.0f%%", r.Score, gradeOf(r), r.Coverage*100)
	if r.Delta != nil {
		fmt.Fprintf(&b, "  change %+.1f", *r.Delta)
	}
	b.WriteString("\n")
	for _, cat := range checks.Categories {
		s, ok := r.Categories[cat]
		if ok {
			fmt.Fprintf(&b, "\n== %s  %.1f/10\n", cat, s)
		} else {
			fmt.Fprintf(&b, "\n== %s  (not evaluated)\n", cat)
		}
		for _, res := range r.Results {
			if res.Category != cat {
				continue
			}
			fmt.Fprintf(&b, "  [%s] %-11s %s\n", icon[res.Status], res.ID, res.Summary)
			for _, d := range res.Details {
				fmt.Fprintf(&b, "         %s\n", d)
			}
		}
	}
	return b.String()
}

// JSON is the machine-readable output.
func JSON(r *checks.Report) string {
	b, _ := json.MarshalIndent(r, "", "  ")
	return string(b)
}

// Markdown is used for job summaries, issues and the published report.
func Markdown(r *checks.Report) string {
	var b strings.Builder
	fmt.Fprintf(&b, "## Lifeline resilience scorecard: %s\n\n", target(r))
	fmt.Fprintf(&b, "**Score: %.1f / 10 (%s)** · coverage %.0f%%", r.Score, gradeOf(r), r.Coverage*100)
	if r.Delta != nil {
		fmt.Fprintf(&b, " · change since last scan: %+.1f", *r.Delta)
	}
	fmt.Fprintf(&b, " · %s\n\n", r.GeneratedAt.Format("2006-01-02 15:04 UTC"))
	b.WriteString("| Area | Score |\n|---|---|\n")
	for _, cat := range checks.Categories {
		if s, ok := r.Categories[cat]; ok {
			fmt.Fprintf(&b, "| %s | %.1f |\n", cat, s)
		} else {
			fmt.Fprintf(&b, "| %s | not evaluated |\n", cat)
		}
	}
	b.WriteString("\n| | Check | Result |\n|---|---|---|\n")
	for _, res := range r.Results {
		fmt.Fprintf(&b, "| %s | **%s** %s | %s |\n", emoji[res.Status], res.ID, res.Title, esc(res.Summary))
	}
	var todo []checks.Result
	for _, res := range r.Results {
		if res.Status == checks.Fail || res.Status == checks.Warn {
			todo = append(todo, res)
		}
	}
	sort.SliceStable(todo, func(i, j int) bool {
		if todo[i].Status != todo[j].Status {
			return todo[i].Status == checks.Fail
		}
		return todo[i].Weight > todo[j].Weight
	})
	if len(todo) > 0 {
		b.WriteString("\n### What to fix first\n\n")
		for i, res := range todo {
			fmt.Fprintf(&b, "%d. **%s %s** - %s\n", i+1, res.ID, res.Title, res.Remediation)
			for _, d := range res.Details {
				fmt.Fprintf(&b, "   - %s\n", esc(d))
			}
		}
	}
	b.WriteString("\n<sub>Generated by [Lifeline](https://github.com/ObaidAbdullah16/lifeline). Checks marked ⏭️ need a token, a domain or a lifeline.yml.</sub>\n")
	return b.String()
}

func esc(s string) string { return strings.ReplaceAll(s, "|", "\\|") }

// Badge is a shields.io endpoint document: https://shields.io/badges/endpoint-badge
func Badge(r *checks.Report) string {
	color := "red"
	message := fmt.Sprintf("%.1f/10", r.Score)
	switch {
	case r.Coverage == 0:
		color, message = "lightgrey", "not evaluated"
	case r.Score >= 8.5:
		color = "brightgreen"
	case r.Score >= 7:
		color = "green"
	case r.Score >= 5:
		color = "yellow"
	}
	b, _ := json.Marshal(map[string]any{
		"schemaVersion": 1,
		"label":         "lifeline",
		"message":       message,
		"color":         color,
	})
	return string(b)
}

// SARIF reports warn/fail results so they appear in GitHub code scanning.
func SARIF(r *checks.Report, all []checks.Check) string {
	var rules []map[string]any
	index := map[string]int{}
	for i, c := range all {
		index[c.ID] = i
		sev := "5.0"
		switch {
		case c.Weight >= 10:
			sev = "8.0"
		case c.Weight >= 6:
			sev = "6.5"
		case c.Weight <= 3:
			sev = "3.0"
		}
		rules = append(rules, map[string]any{
			"id":               c.ID,
			"name":             strings.ReplaceAll(strings.ToLower(c.Title), " ", "-"),
			"shortDescription": map[string]string{"text": c.Title},
			"help":             map[string]string{"text": c.Remediation, "markdown": c.Remediation},
			"helpUri":          "https://github.com/ObaidAbdullah16/lifeline/blob/main/docs/checks.md#" + strings.ToLower(c.ID),
			"properties":       map[string]any{"security-severity": sev, "tags": []string{"security", "resilience", c.Category}},
		})
	}
	var results []map[string]any
	for _, res := range r.Results {
		if res.Status != checks.Fail && res.Status != checks.Warn {
			continue
		}
		loc := res.Location
		if loc == "" {
			loc = "README.md"
		}
		level := "warning"
		if res.Status == checks.Fail {
			level = "error"
		}
		msg := res.Summary
		if len(res.Details) > 0 {
			msg += "\n" + strings.Join(res.Details, "\n")
		}
		results = append(results, map[string]any{
			"ruleId":    res.ID,
			"ruleIndex": index[res.ID],
			"level":     level,
			"message":   map[string]string{"text": msg},
			"locations": []any{map[string]any{"physicalLocation": map[string]any{
				"artifactLocation": map[string]string{"uri": loc},
				"region":           map[string]int{"startLine": 1},
			}}},
		})
	}
	if results == nil {
		results = []map[string]any{}
	}
	doc := map[string]any{
		"$schema": "https://json.schemastore.org/sarif-2.1.0.json",
		"version": "2.1.0",
		"runs": []any{map[string]any{
			"tool": map[string]any{"driver": map[string]any{
				"name": "lifeline", "version": r.Version,
				"informationUri": "https://github.com/ObaidAbdullah16/lifeline",
				"rules":          rules,
			}},
			"results": results,
		}},
	}
	b, _ := json.MarshalIndent(doc, "", "  ")
	return string(b)
}
